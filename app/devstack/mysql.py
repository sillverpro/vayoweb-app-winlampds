# ---------------------------------------------------------------- databases (read from the data folder)

SYSTEM_DBS = {"mysql", "performance_schema", "sys", "information_schema"}


def _db_name(folder: str) -> str:
    # MySQL stores special characters in folder names as @xxxx (e.g. my@002ddb = my-db).
    return re.sub(r"@([0-9a-f]{4})", lambda m: chr(int(m.group(1), 16)), folder)


def databases(include_system=False) -> list[dict]:
    """Every database with its size on disk. Works whether MySQL runs or not."""
    out = []
    if not paths.MYSQL_DATA.is_dir():
        return out
    for d in paths.MYSQL_DATA.iterdir():
        if not d.is_dir() or d.name.startswith("#"):
            continue
        name = _db_name(d.name)
        if name in SYSTEM_DBS and not include_system:
            continue
        size, newest, tables = 0, 0.0, set()
        for f in d.iterdir():
            try:
                st = f.stat()
            except OSError:
                continue
            size += st.st_size
            newest = max(newest, st.st_mtime)
            if f.suffix.lower() in (".ibd", ".myd"):
                tables.add(f.stem.split("#")[0].lower())   # partitions are table#p#p0.ibd
        out.append({"name": name, "size": size, "tables": len(tables), "modified": newest,
                    "system": name in SYSTEM_DBS})
    return sorted(out, key=lambda x: x["name"].lower())


def export_db(cfg: dict, name: str, dest, job=None, create_missing=False, standalone=True) -> dict:
    """mysqldump one database to a .sql file (MySQL must be running). With a job, polls the growing
    file for a progress percentage (against the database's on-disk size - a rough but honest estimate).
    standalone=True (the normal Export/backup) embeds CREATE DATABASE/USE `name`, so the file restores
    itself under its own name. standalone=False (used by clone/export-site, which import under a
    *different* database name) dumps tables and data only, with no database name baked in."""
    exists = {d["name"] for d in databases()}
    if name not in exists:
        if not create_missing:
            raise ValueError(f"No database {name}")
        create_database(cfg, name)
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    args = [str(bin_dir() / "mysqldump.exe"), "-uroot", "-h127.0.0.1", f"-P{cfg['ports']['mysql']}"]
    if cfg.get("mysql_root_password"):
        args.append(f"-p{cfg['mysql_root_password']}")
    args += ["--single-transaction", "--routines", "--triggers", "--events", "--set-gtid-purged=OFF",
             "--default-character-set=utf8mb4", "--add-drop-table", f"--result-file={dest}"]
    args += ["--databases", name] if standalone else [name]
    if job is None:
        res = run(args, timeout=3600)
    else:
        db_size = next((d["size"] for d in databases() if d["name"] == name), 0)
        job.update(f"Exporting {name}", 0)
        proc = subprocess.Popen(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                                errors="replace", creationflags=CREATE_NO_WINDOW)
        while proc.poll() is None:
            got = dest.stat().st_size if dest.exists() else 0
            job.update(f"Exporting {name} ({got / 1e6:.0f} MB)", min(got / db_size, 0.95) if db_size else None)
            time.sleep(0.3)
        out, err = proc.communicate()
        res = subprocess.CompletedProcess(args, proc.returncode, out, err)
    if res.returncode != 0:
        dest.unlink(missing_ok=True)
        err = "\n".join(l for l in res.stderr.splitlines() if "password on the command line" not in l)
        raise RuntimeError(err.strip() or "mysqldump failed")
    if job:
        job.update(f"Exporting {name}", 1)
    return {"path": paths.fwd(dest), "size": dest.stat().st_size}


def import_sql(cfg: dict, path: str, job, database: str | None = None, create_missing=False) -> dict:
    """Stream a .sql or .sql.gz file into the mysql client, with progress from bytes read (real % for
    plain .sql; indeterminate for .gz, since the read position is the decompressed size, not the file's)."""
    src = Path(path)
    if not src.is_file():
        raise ValueError(f"File not found: {src}")
    if database and create_missing and database not in {d["name"] for d in databases()}:
        create_database(cfg, database)
    args = _client_args(cfg) + (["--default-character-set=utf8mb4"]) + ([database] if database else [])
    total = src.stat().st_size
    gz = src.suffix.lower() == ".gz"
    proc = subprocess.Popen(args, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            creationflags=CREATE_NO_WINDOW)
    job.update(f"Importing {src.name}", 0)
    got, last = 0, 0.0
    opener = gzip.open if gz else open
    try:
        with opener(src, "rb") as fh:
            while chunk := fh.read(1 << 20):
                proc.stdin.write(chunk)
                got += len(chunk)
                if time.time() - last > 0.3:
                    last = time.time()
                    job.update(f"Importing {src.name} ({got / 1e6:.0f} MB)", None if gz else min(got / total, 0.98))
    finally:
        proc.stdin.close()
    out, err = proc.communicate(timeout=3600)
    if proc.returncode != 0:
        raise RuntimeError((err.decode("utf-8", errors="replace") or "mysql import failed").strip())
    job.update(f"Imported {src.name}", 1)
    return {"database": database, "size": total}


def backup_path(name: str) -> Path:
    return paths.DB_EXPORTS / f"{name}-{time.strftime('%Y%m%d-%H%M%S')}.sql"


def exports() -> list[dict]:
    """.sql files in data/exports, newest first."""
    if not paths.DB_EXPORTS.is_dir():
        return []
    files = sorted(paths.DB_EXPORTS.glob("*.sql"), key=lambda f: f.stat().st_mtime, reverse=True)
    return [{"name": f.name, "path": paths.fwd(f), "size": f.stat().st_size, "modified": f.stat().st_mtime} for f in files]


def backups() -> list[dict]:
    """Old data folders kept by an import or a MySQL upgrade (data/mysql.bak-*)."""
    out = []
    for d in sorted(paths.MYSQL_DATA.parent.glob("mysql.bak-*")):
        if d.is_dir():
            out.append({"name": d.name, "path": paths.fwd(d),
                        "size": sum(f.stat().st_size for f in d.rglob("*") if f.is_file())})
    return out


def delete_backup(name: str):
    d = paths.MYSQL_DATA.parent / name
    if not name.startswith("mysql.bak-") or d.parent != paths.MYSQL_DATA.parent or not d.is_dir():
        raise ValueError("not a backup folder")
    shutil.rmtree(d)


# ---------------------------------------------------------------- scheduled backups (Settings > backup)

def last_backups() -> dict[str, float]:
    """{db name: mtime of its newest scheduled/manual .sql in data/exports}."""
    out = {}
    if not paths.DB_EXPORTS.is_dir():
        return out
    for f in [*paths.DB_EXPORTS.glob("*.sql"), *AUTO_BACKUPS.glob("*.sql")]:
        m = re.match(r"^(.+)-\d{8}-\d{6}\.sql$", f.name)
        if not m:
            continue
        name = m.group(1)
        out[name] = max(out.get(name, 0.0), f.stat().st_mtime)
    return out


AUTO_BACKUPS = paths.DB_EXPORTS / "auto"   # scheduled dumps live apart, so pruning never touches manual ones


def _prune_backups(name: str, keep: int):
    if keep <= 0:
        return
    own = re.compile(rf"^{re.escape(name)}-\d{{8}}-\d{{6}}\.sql$")   # not "shop-old-..." when pruning "shop"
    files = sorted((f for f in AUTO_BACKUPS.glob("*.sql") if own.match(f.name)), key=lambda f: f.stat().st_mtime)
    for f in files[:-keep]:
        f.unlink(missing_ok=True)


def run_due_backups(cfg: dict):
    """Dump every configured database that hasn't been backed up in the last 24h. Called from a background
    thread (see start_backup_thread) and safe to call any time - it's a no-op unless backup.enabled is set."""
    from . import services
    conf = cfg.get("backup") or {}
    if not conf.get("enabled") or services.status(cfg, "mysql") != "running":
        return
    all_names = [d["name"] for d in databases()]
    names = [n for n in (conf.get("dbs") or all_names) if n in all_names and n not in SYSTEM_DBS]
    last = last_backups()
    keep = int(conf.get("keep") or 7)
    for name in names:
        if time.time() - last.get(name, 0) < 86400:
            continue
        try:
            export_db(cfg, name, AUTO_BACKUPS / backup_path(name).name)
            _prune_backups(name, keep)
        except Exception:
            pass   # next hourly check tries again; one bad database shouldn't stop the others


_backup_thread_started = False


def start_backup_thread():
    """Start the once-per-app scheduled-backup thread (also runs while minimized to the tray)."""
    global _backup_thread_started
    if _backup_thread_started:
        return
    _backup_thread_started = True

    def loop():
        from . import settings
        while True:
            try:
                run_due_backups(settings.load())
            except Exception:
                pass
            time.sleep(3600)   # hourly check; a dump only actually runs once 24h have passed for that database

    threading.Thread(target=loop, daemon=True, name="backup-scheduler").start()
