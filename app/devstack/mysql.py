def bin_dir():
    d = paths.mysql_dir()
    if not d:
        raise RuntimeError("MySQL is not installed in bin/mysql")
    return d / "bin"


def mysqld_exe():
    return bin_dir() / "mysqld.exe"


def write_my_ini(cfg: dict, base=None, path=None):
    base = base or paths.mysql_dir()
    path = path or paths.MY_INI
    port = cfg["ports"]["mysql"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"""# Generated by DevStack - changes here are overwritten. Use the app instead.
[client]
port={port}
default-character-set=utf8mb4

[mysqld]
port={port}
bind-address=127.0.0.1,::1
basedir="{paths.fwd(base)}"
datadir="{paths.fwd(paths.MYSQL_DATA)}"
log-error="{paths.fwd(paths.LOGS / 'mysql_error.log')}"
pid-file="{paths.fwd(paths.LOGS / 'mysql.pid')}"
lc_messages_dir="{paths.fwd(base / 'share')}"
lc_messages=en_US
character-set-server=utf8mb4
max_allowed_packet=256M
innodb_buffer_pool_size=256M
table_definition_cache=600
secure_file_priv=""
mysqlx=0
""", encoding="utf-8")


def validate_config(base) -> tuple[bool, str]:
    """Check my.ini against another MySQL folder before switching to it."""
    ini = paths.TMP / "my-test.ini"
    from . import settings
    write_my_ini(settings.load(), base, ini)
    r = run([str(base / "bin" / "mysqld.exe"), f"--defaults-file={ini}", "--validate-config"], timeout=60)
    return r.returncode == 0, (r.stdout + r.stderr).strip()


def datadir_initialized() -> bool:
    return (paths.MYSQL_DATA / "mysql").is_dir()


def init_datadir():
    """Create an empty data directory: root@localhost with no password (dev only)."""
    if datadir_initialized():
        return
    paths.MYSQL_DATA.mkdir(parents=True, exist_ok=True)
    if any(paths.MYSQL_DATA.iterdir()):
        raise RuntimeError(f"{paths.MYSQL_DATA} is not empty but has no MySQL system tables")
    r = run([str(mysqld_exe()), f"--defaults-file={paths.MY_INI}", "--initialize-insecure", "--console"],
            timeout=600)
    if r.returncode != 0 or not datadir_initialized():
        raise RuntimeError("MySQL initialization failed:\n" + (r.stdout + r.stderr)[-3000:])


def import_datadir(src: str):
    """Replace our data directory with a copy of another (stopped) MySQL's, e.g. from another local server.

    The old data directory is kept as data/mysql.bak-<timestamp>.
    """
    from pathlib import Path
    src = Path(src)
    if not (src / "mysql").is_dir():
        raise ValueError(f"{src} does not look like a MySQL data directory")
    if paths.MYSQL_DATA.exists() and any(paths.MYSQL_DATA.iterdir()):
        paths.MYSQL_DATA.rename(paths.MYSQL_DATA.with_name(f"mysql.bak-{time.strftime('%Y%m%d-%H%M%S')}"))
    shutil.copytree(src, paths.MYSQL_DATA, ignore=shutil.ignore_patterns("*.pid", "*.err"))


_IDENT_RE = re.compile(r"^[a-z0-9_]+$")


def _client_args(cfg: dict) -> list[str]:
    args = [str(bin_dir() / "mysql.exe"), "-uroot", "-h127.0.0.1", f"-P{cfg['ports']['mysql']}"]
    if cfg.get("mysql_root_password"):
        args.append(f"-p{cfg['mysql_root_password']}")
    return args


def run_sql(cfg: dict, sql: str, database: str | None = None, timeout=60) -> str:
    args = _client_args(cfg) + ([database] if database else []) + ["-e", sql]
    r = run(args, timeout=timeout)
    if r.returncode != 0:
        err = "\n".join(l for l in (r.stderr or r.stdout).splitlines() if "password on the command line" not in l)
        raise RuntimeError(err.strip() or "mysql command failed")
    return r.stdout


def _ident(name: str) -> str:
    """Backtick-quote an identifier already restricted to [a-z0-9_], doubling any backtick just in case."""
    return "`" + name.replace("`", "``") + "`"


def _sqlstr(s: str) -> str:
    """Escape a string for a single-quoted SQL literal (user names, hosts, passwords)."""
    return s.replace("\\", "\\\\").replace("'", "''")


def _rows(cfg: dict, sql: str, database: str | None = None) -> list[dict]:
    """Run a SELECT and turn the tab-separated `mysql -e` output into a list of {column: value} dicts."""
    out = run_sql(cfg, sql, database)
    lines = out.splitlines()
    if not lines:
        return []
    headers = lines[0].split("\t")
    return [dict(zip(headers, line.split("\t"))) for line in lines[1:]]


def create_database(cfg: dict, name: str, user: str | None = None) -> dict:
    """Create a database (utf8mb4) and, optionally, a user with a random password granted on it (localhost + 127.0.0.1)."""
    name = name.strip().lower()
    if not _IDENT_RE.match(name):
        raise ValueError("Database name: letters, numbers and underscore only")
    if name in SYSTEM_DBS:
        raise ValueError(f"{name} is a reserved name")
    sql = ""
    creds = {"database": name}
    if user:
        user = user.strip().lower()
        if not _IDENT_RE.match(user):
            raise ValueError("User name: letters, numbers and underscore only")
        password = secrets.token_urlsafe(18)
        for host in ("localhost", "127.0.0.1"):
            pw = password.replace("'", "''")
            # Plain CREATE USER: an existing user keeps its password, so fail rather than hand out a wrong one.
            sql += f"CREATE USER '{user}'@'{host}' IDENTIFIED BY '{pw}';"
        sql += f"CREATE DATABASE IF NOT EXISTS {_ident(name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
        sql += "".join(f"GRANT ALL PRIVILEGES ON {_ident(name)}.* TO '{user}'@'{h}';" for h in ("localhost", "127.0.0.1"))
        creds.update(user=user, password=password, host="127.0.0.1", port=cfg["ports"]["mysql"])
    else:
        sql = f"CREATE DATABASE IF NOT EXISTS {_ident(name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
    try:
        run_sql(cfg, sql)
    except RuntimeError as e:
        if "CREATE USER failed" in str(e):
            raise RuntimeError(f"MySQL user {user} already exists - pick another user name") from None
        raise
    return creds


SYSTEM_USERS = {"mysql.sys", "mysql.session", "mysql.infoschema"}
_GRANTEE_RE = re.compile(r"^'(.*)'@'(.*)'$")


def _schema_grants(cfg: dict) -> list[tuple[str, str, str]]:
    """[(user, host, database)] from information_schema, one row per user/database that has any privilege on it."""
    rows = _rows(cfg, "SELECT GRANTEE, TABLE_SCHEMA FROM information_schema.SCHEMA_PRIVILEGES GROUP BY GRANTEE, TABLE_SCHEMA;")
    out = []
    for r in rows:
        m = _GRANTEE_RE.match(r["GRANTEE"])
        if not m:
            continue
        out.append((m.group(1), m.group(2), r["TABLE_SCHEMA"]))
    return out


def users(cfg: dict) -> list[dict]:
    """Every MySQL user (excluding internal system accounts) with the databases it has privileges on.
    root is included and flagged - it's the one user the UI won't let you delete."""
    rows = _rows(cfg, "SELECT User, Host FROM mysql.user ORDER BY User, Host;")
    grants: dict[str, set[str]] = {}
    for user, host, db in _schema_grants(cfg):
        if db in SYSTEM_DBS:
            continue
        grants.setdefault(f"{user}@{host}", set()).add(db)
    out = []
    for r in rows:
        user, host = r["User"], r["Host"]
        if user in SYSTEM_USERS:
            continue
        out.append({"user": user, "host": host, "root": user == "root",
                    "databases": sorted(grants.get(f"{user}@{host}", set()))})
    return out


def db_users(cfg: dict) -> dict[str, list[str]]:
    """{database name: ["user@host", ...]} for the Database page's per-database "User" column.
    root and system accounts are left out - every database is implicitly root's."""
    out: dict[str, list[str]] = {}
    for user, host, db in _schema_grants(cfg):
        if user == "root" or user in SYSTEM_USERS or db in SYSTEM_DBS:
            continue
        out.setdefault(db, []).append(f"{user}@{host}")
    return out


def set_user_password(cfg: dict, user: str, host: str, password: str):
    """Change a MySQL user's password. For root, the caller must also update mysql_root_password in
    settings - otherwise every other feature that talks to MySQL as root would start failing."""
    if not password:
        raise ValueError("Enter a password")
    # root exists once per host (localhost, 127.0.0.1, ::1) and the app has one root password: change them all together.
    hosts = [r["Host"] for r in _rows(cfg, "SELECT Host FROM mysql.user WHERE User = 'root';")] if user == "root" else [host]
    run_sql(cfg, "".join(f"ALTER USER '{_sqlstr(user)}'@'{_sqlstr(h)}' IDENTIFIED BY '{_sqlstr(password)}';" for h in hosts))


def drop_user(cfg: dict, user: str, host: str):
    if user == "root":
        raise ValueError("The root user can't be deleted")
    run_sql(cfg, f"DROP USER '{_sqlstr(user)}'@'{_sqlstr(host)}';")


def shutdown(cfg: dict) -> bool:
    args = [str(bin_dir() / "mysqladmin.exe"), "-uroot", "-h127.0.0.1", f"-P{cfg['ports']['mysql']}"]
    if cfg.get("mysql_root_password"):
        args.append(f"-p{cfg['mysql_root_password']}")
    return run(args + ["shutdown"], timeout=30).returncode == 0


