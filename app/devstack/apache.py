"""Generates Apache config: one httpd.conf plus one file per site, each with its own PHP version via mod_fcgid."""
import os
import shutil

from . import paths, php, ssl
from .settings import DEFAULT_SITE
from .winutil import run

MODULES = [
    "actions", "alias", "allowmethods", "auth_basic", "authn_core", "authn_file", "authz_core",
    "authz_groupfile", "authz_host", "authz_user", "autoindex", "deflate", "dir", "env", "expires",
    "fcgid", "filter", "headers", "http2", "include", "log_config", "mime", "negotiation", "proxy",
    "proxy_http", "proxy_wstunnel", "rewrite", "setenvif", "socache_shmcb", "ssl",
]

HEADER = "# Generated by DevStack - changes here are overwritten. Use the app instead.\n"


def httpd_exe():
    d = paths.apache_dir()
    if not d:
        raise RuntimeError("Apache is not installed in bin/apache")
    return d / "bin" / "httpd.exe"


def render_httpd_conf(cfg: dict, root=None) -> str:
    root = root or paths.apache_dir()
    p = cfg["ports"]
    windir = os.environ.get("SystemRoot", r"C:\Windows")
    mods = "\n".join(f'LoadModule {m}_module modules/mod_{m}.so' for m in MODULES
                     if (root / "modules" / f"mod_{m}.so").exists())
    return f"""{HEADER}
Define DEVSTACK "{paths.fwd(paths.ROOT)}"
ServerRoot "{paths.fwd(root)}"
Listen {p['http']}
Listen {p['https']}
ServerName localhost:{p['http']}
ServerAdmin admin@localhost
ServerTokens Prod
ServerSignature Off

{mods}

PidFile "{paths.fwd(paths.LOGS / 'httpd.pid')}"
ErrorLog "{paths.fwd(paths.LOGS / 'apache_error.log')}"
LogLevel warn
LogFormat "%h %l %u %t \\"%r\\" %>s %b \\"%{{Referer}}i\\" \\"%{{User-Agent}}i\\"" combined
CustomLog "{paths.fwd(paths.LOGS / 'apache_access.log')}" combined

ThreadsPerChild 150
MaxConnectionsPerChild 0
Timeout 300
KeepAlive On
AcceptFilter http none
AcceptFilter https none
EnableSendfile off
EnableMMAP off

TypesConfig conf/mime.types
AddType application/x-compress .Z
AddType application/x-gzip .gz .tgz
AddDefaultCharset UTF-8
DirectoryIndex index.php index.html index.htm

<Directory />
    AllowOverride None
    Require all denied
</Directory>
<Files ".ht*">
    Require all denied
</Files>

# ---- PHP via FastCGI (each site picks its php-cgi.exe) ----
FcgidInitialEnv SystemRoot "{paths.fwd(windir)}"
FcgidInitialEnv SystemDrive "{os.environ.get('SystemDrive', 'C:')}"
FcgidInitialEnv windir "{paths.fwd(windir)}"
FcgidInitialEnv TEMP "{paths.fwd(paths.TMP)}"
FcgidInitialEnv TMP "{paths.fwd(paths.TMP)}"
FcgidInitialEnv PHP_FCGI_MAX_REQUESTS 1000
FcgidMaxRequestsPerProcess 1000
FcgidMaxRequestLen 1073741824
FcgidIOTimeout 600
FcgidBusyTimeout 600
FcgidConnectTimeout 20
FcgidIdleTimeout 600

# ---- SSL ----
SSLRandomSeed startup builtin
SSLRandomSeed connect builtin
SSLProtocol all -SSLv3 -TLSv1 -TLSv1.1
SSLSessionCache "shmcb:{paths.fwd(paths.LOGS / 'ssl_scache')}(512000)"
SSLSessionCacheTimeout 300

# ---- HTTP/2 (browsers only use it over HTTPS) ----
<IfModule http2_module>
    Protocols h2 http/1.1
</IfModule>

IncludeOptional "{paths.fwd(paths.SITES_CONF)}/*.conf"
"""


def _php_block(ver: str, domain: str) -> str:
    d = paths.fwd(php.php_dir(ver))
    scan_dir = paths.fwd(paths.PHP_SITE_CONFIG / domain)
    return f"""    FcgidInitialEnv PHPRC "{d}"
    FcgidInitialEnv PHP_INI_SCAN_DIR "{scan_dir}"
    FcgidWrapper "{d}/php-cgi.exe" .php
    <FilesMatch "\\.php$">
        SetHandler fcgid-script
    </FilesMatch>"""


def write_php_site_ini(domain: str):
    """Per-site php.ini snippet (PHP_INI_SCAN_DIR points here): its own error log, keyed by the domain
    so mod_fcgid spawns a separate php-cgi process class per site instead of sharing one across vhosts."""
    d = paths.PHP_SITE_CONFIG / domain
    d.mkdir(parents=True, exist_ok=True)
    log = paths.fwd(paths.SITE_LOGS / f"{domain}-php.log")
    text = f'; Generated by DevStack - changes here are overwritten.\nerror_log = "{log}"\nlog_errors = On\n'
    ini = d / "devstack.ini"
    if not ini.exists() or ini.read_text(encoding="utf-8") != text:
        ini.write_text(text, encoding="utf-8")


def _dir_block(path: str, lan: bool = False) -> str:
    # LAN-shared vhosts accept any client; normal ones only the machine itself (127.x, ::1, the LAN IP).
    return f"""    <Directory "{path}">
        Options Indexes FollowSymLinks ExecCGI
        AllowOverride All
        Require {"all granted" if lan else "local"}
    </Directory>"""


def render_site(cfg: dict, site: dict) -> str:
    domain, root = site["domain"], paths.fwd(site["root"])
    is_default = site["name"] == DEFAULT_SITE
    aliases = [f"www.{domain}"] + (["localhost", "127.0.0.1"] if is_default else []) + list(site.get("aliases", []))
    log = paths.fwd(paths.SITE_LOGS / domain)

    def vhost_body(lan=False):
        b = [
            f"    ServerName {domain}",
            f"    ServerAlias {' '.join(aliases)}",
            f'    DocumentRoot "{root}"',
            f'    ErrorLog "{log}-error.log"',
            _dir_block(root, lan),
            _php_block(site["php"], domain),
        ]
        if site.get("apache_extra"):
            b.append(site["apache_extra"])
        if is_default and paths.PMA.is_dir() and not lan:
            pma = paths.fwd(paths.PMA)
            b += [f'    Alias /phpmyadmin "{pma}"', _dir_block(pma)]
        return "\n".join(b)

    body = vhost_body()
    out = [HEADER, f"<VirtualHost *:{cfg['ports']['http']}>\n{body}\n</VirtualHost>\n"]
    if site.get("ssl"):
        crt, key = ssl.cert_paths(domain)
        out.append(f"""<VirtualHost *:{cfg['ports']['https']}>
{body}
    SSLEngine on
    SSLCertificateFile "{paths.fwd(crt)}"
    SSLCertificateKeyFile "{paths.fwd(key)}"
</VirtualHost>
""")
    if site.get("lan_port"):
        # Its own Listen: each lan_port is unique to one site, so this can't collide with another site's.
        out.append(f'Listen {site["lan_port"]}\n<VirtualHost *:{site["lan_port"]}>\n{vhost_body(lan=True)}\n</VirtualHost>\n')
    return "\n".join(out)


def site_conf_path(site: dict):
    # The default site sorts first so it also answers unknown host names.
    prefix = "000-" if site["name"] == DEFAULT_SITE else ""
    return paths.SITES_CONF / f"{prefix}{site['domain']}.conf"


def _write_if_changed(f, text: str):
    # Unchanged files keep their mtime, so reconcile() doesn't restart Apache for nothing.
    if not f.exists() or f.read_text(encoding="utf-8") != text:
        f.write_text(text, encoding="utf-8")


def write_all(cfg: dict):
    paths.APACHE_CONF.parent.mkdir(parents=True, exist_ok=True)
    paths.SITES_CONF.mkdir(parents=True, exist_ok=True)
    _write_if_changed(paths.APACHE_CONF, render_httpd_conf(cfg))
    wanted = set()
    for site in cfg["sites"]:
        if site.get("ssl"):
            extra = (["localhost", "127.0.0.1", "::1"] if site["name"] == DEFAULT_SITE else []) + list(site.get("aliases", []))
            ssl.ensure_site_cert(site["domain"], extra)
        write_php_site_ini(site["domain"])
        f = site_conf_path(site)
        _write_if_changed(f, render_site(cfg, site))
        wanted.add(f.name)
    for f in paths.SITES_CONF.glob("*.conf"):
        if f.name not in wanted:
            f.unlink()
    wanted_domains = {s["domain"] for s in cfg["sites"]}
    if paths.PHP_SITE_CONFIG.is_dir():
        for d in paths.PHP_SITE_CONFIG.iterdir():
            if d.is_dir() and d.name not in wanted_domains:
                shutil.rmtree(d, ignore_errors=True)


def test_config(root=None, cfg=None) -> tuple[bool, str]:
    """httpd -t on the current config, or on a config rendered for another Apache folder (before switching)."""
    conf = paths.APACHE_CONF
    if root:
        conf = paths.TMP / "httpd-test.conf"
        conf.write_text(render_httpd_conf(cfg, root), encoding="utf-8")
    root = root or paths.apache_dir()
    r = run([str(root / "bin" / "httpd.exe"), "-t", "-f", str(conf)], cwd=str(root))
    return r.returncode == 0, (r.stdout + r.stderr).strip()
